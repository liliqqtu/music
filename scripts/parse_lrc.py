"""
Parse LRC and Bilingual Translations into TypeScript Dataset
"""

import argparse
import os
import re

def parse_time_to_seconds(time_str: str) -> float:
    parts = time_str.split(":")
    mins = float(parts[0])
    secs = float(parts[1])
    return mins * 60 + secs

def parse_lrc(lrc_path: str, zh_path: str = None, fps: int = 30) -> list[dict]:
    with open(lrc_path, "r", encoding="utf-8") as f:
        lrc_lines = f.readlines()

    zh_lines = []
    if zh_path and os.path.exists(zh_path):
        with open(zh_path, "r", encoding="utf-8") as f:
            zh_lines = [line.strip() for line in f if line.strip()]

    parsed = []
    pattern = re.compile(r"\[(\d{2}:\d{2}(?:\.\d{2,3})?)\](.*)")

    for line in lrc_lines:
        match = pattern.match(line.strip())
        if match:
            t_str, text = match.groups()
            text = text.strip()
            if text:
                parsed.append({
                    "time": parse_time_to_seconds(t_str),
                    "text": text
                })

    parsed.sort(key=lambda x: x["time"])

    lyrics = []
    for i, item in enumerate(parsed):
        start_sec = item["time"]
        start_frame = int(round(start_sec * fps))

        if i < len(parsed) - 1:
            end_sec = parsed[i + 1]["time"]
            end_frame = int(round(end_sec * fps)) - 1
        else:
            end_frame = start_frame + int(fps * 5)

        zh_text = zh_lines[i] if i < len(zh_lines) else ""

        lyrics.append({
            "id": f"l_{i+1:02d}",
            "startFrame": start_frame,
            "endFrame": end_frame,
            "startTime": round(start_sec, 2),
            "text": item["text"],
            "zhText": zh_text
        })

    return lyrics

def generate_typescript_lyrics(lyrics: list[dict], out_path: str):
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    ts_content = """// Auto-generated by scripts/parse_lrc.py

export interface LyricLine {
  readonly id: string;
  readonly startFrame: number;
  readonly endFrame: number;
  readonly startTime: number;
  readonly text: string;
  readonly zhText?: string;
}

export const LYRIC_LINES: LyricLine[] = """
    import json
    ts_content += json.dumps(lyrics, ensure_ascii=False, indent=2) + ";\n"

    with open(out_path, "w", encoding="utf-8") as f:
        f.write(ts_content)
    print(f"Generated {len(lyrics)} lyric lines to {out_path}")

def main():
    parser = argparse.ArgumentParser(description="Parse LRC to TypeScript")
    parser.add_argument("--lrc", required=True, help="Path to .lrc file")
    parser.add_argument("--zh", default=None, help="Path to translation .txt file")
    parser.add_argument("--out", default="src/data/lyrics.ts", help="Output .ts file path")
    parser.add_argument("--fps", type=int, default=30, help="Video FPS (default: 30)")
    args = parser.parse_args()

    lyrics = parse_lrc(args.lrc, args.zh, fps=args.fps)
    generate_typescript_lyrics(lyrics, args.out)

if __name__ == "__main__":
    main()
